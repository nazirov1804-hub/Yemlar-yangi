const sourceByNode = new WeakMap();
const sourceByAttribute = new WeakMap();
let activeLanguage = "uz";
let activeObserver;
let observerUsers = 0;

function translateNode(node, language) {
  const previous = sourceByNode.get(node);
  const current = node.data;
  const source = previous?.rendered === current ? previous.source : current;
  const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match || !match[2]) return;
  const rendered = `${match[1]}${translateText(match[2], language)}${match[3]}`;
  sourceByNode.set(node, { source, rendered });
  if (rendered !== current) node.data = rendered;
}

function translateAttribute(element, attribute, language) {
  const previousAttributes = sourceByAttribute.get(element) || new Map();
  const previous = previousAttributes.get(attribute);
  const current = element.getAttribute(attribute);
  const source = previous?.rendered === current ? previous.source : current;
  const rendered = translateText(source, language);
  previousAttributes.set(attribute, { source, rendered });
  sourceByAttribute.set(element, previousAttributes);
  if (rendered !== current) element.setAttribute(attribute, rendered);
}

function visit(node, language) {
  if (node.nodeType === Node.TEXT_NODE) {
    translateNode(node, language);
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  if (node.matches("[data-language-picker]")) return;
  for (const attribute of ["aria-label", "title", "placeholder", "alt"]) {
    if (node.hasAttribute(attribute)) translateAttribute(node, attribute, language);
  }
  for (const child of node.childNodes) visit(child, language);
}

export function observeTranslations(language) {
  activeLanguage = language;
  document.documentElement.lang =
    activeLanguage === "uz" ? "uz" : activeLanguage === "ru" ? "ru" : "en";
  visit(document.body, activeLanguage);
  observerUsers += 1;
  if (!activeObserver) {
    activeObserver = new MutationObserver((records) => {
      for (const record of records) {
        if (record.type === "characterData") {
          translateNode(record.target, activeLanguage);
        } else if (record.type === "attributes") {
          if (record.target.hasAttribute(record.attributeName)) {
            translateAttribute(record.target, record.attributeName, activeLanguage);
          }
        } else {
          for (const node of record.addedNodes) visit(node, activeLanguage);
        }
      }
    });
    activeObserver.observe(document.body, {
      childList: true,
      characterData: true,
      subtree: true,
      attributes: true,
      attributeFilter: ["aria-label", "title", "placeholder", "alt"],
    });
  }
  return () => {
    observerUsers = Math.max(0, observerUsers - 1);
    if (observerUsers === 0) {
      activeObserver?.disconnect();
      activeObserver = undefined;
    }
  };
}
