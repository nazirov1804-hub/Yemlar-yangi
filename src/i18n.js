const catalogs = Object.fromEntries(
  ["ru", "en"].map((language, index) => [
    language,
    new Map(
      [...entries]
        .reverse()
        .map(([uzbek, russian, english]) => [
          uzbek,
          index === 0 ? russian : english,
        ]),
    ),
  ]),
);
const sourceByTranslation = Object.fromEntries(
  ["ru", "en"].map((language) => [
    language,
    new Map(
      [...entries].reverse().map(([source, russian, english]) => [
        language === "ru" ? russian : english,
        source,
      ]),
    ),
  ]),
);

const translationPhrases = Object.fromEntries(
  ["ru", "en"].map((language) => [
    language,
    [...new Map([...entries].reverse().map((entry) => [entry[0], entry])).values()]
      .filter(([source]) => source.length >= 14 && /\s/.test(source))
      .sort((left, right) => right[0].length - left[0].length)
      .map(([source, russian, english]) => [
        source,
        language === "ru" ? russian : english,
      ]),
  ]),
);

const phraseExpressions = new Map();
function replacePhrase(text, phrase, replacement) {
  let expression = phraseExpressions.get(phrase);
  if (!expression) {
    const pattern = phrase
      .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
      .replace(/\s+/g, "\\s+");
    expression = new RegExp(pattern, "giu");
    phraseExpressions.set(phrase, expression);
  }
  return text.replace(expression, replacement);
}

function translatePartialText(value, language) {
  let canonical = value;
  for (const [source, translated] of translationPhrases[language]) {
    canonical = replacePhrase(canonical, translated, source);
  }
  let translated = canonical;
  for (const [source, target] of translationPhrases[language]) {
    translated = replacePhrase(translated, source, target);
  }
  return translated;
}

function localizeLunchTerm(value, language) {
  const term = language === "ru" ? "обед" : language === "en" ? "lunch" : "tushlik";
  return value.replace(/\babed(ni|ning|ga|dan|da|lar|lari|sini|si)?\b/gi, (match, suffix = "") => {
    const localizedTerm = language === "uz" ? `${term}${suffix}` : term;
    return match[0] === match[0].toLocaleUpperCase()
      ? `${localizedTerm[0].toLocaleUpperCase()}${localizedTerm.slice(1)}`
      : localizedTerm;
  });
}

function localizeUnits(value, language) {
  return value
    .replace(/\bqop\b/gi, (match, offset, text) => {
      if (language === "ru") return "меш.";
      if (language === "uz") return "qop";
      const amount = text.slice(0, offset).match(/(\d+(?:[.,]\d+)?)\s*$/)?.[1];
      const unit = Number(amount) === 1 ? "bag" : "bags";
      return match[0] === match[0].toLocaleUpperCase()
        ? `${unit[0].toLocaleUpperCase()}${unit.slice(1)}`
        : unit;
    })
    .replace(/\bkg\b/gi, language === "ru" ? "кг" : "kg");
}

function russianCount(value, one, few, many) {
  const count = Number(value);
  const remainder100 = count % 100;
  const remainder10 = count % 10;
  const form =
    remainder100 >= 11 && remainder100 <= 14
      ? many
      : remainder10 === 1
        ? one
        : remainder10 >= 2 && remainder10 <= 4
          ? few
          : many;
  return `${value} ${form}`;
}

